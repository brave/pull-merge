/* eslint-disable camelcase */
import { Given, When, Then } from '@cucumber/cucumber'
import { expect } from 'chai'
import fc from 'fast-check'
import { mockState } from '../support/state.mjs'

async function callAnthropic (world) {
  const { default: explainPatch } = await import('../../src/anthropicExplainPatch.js')
  world.error = null
  try {
    world.result = await explainPatch({
      apiKey: world.apiKey ?? 'sk-ant-test',
      patchBody: world.patchBody,
      owner: world.owner,
      repo: world.repo,
      ...(world.models ? { models: world.models } : {}),
      ...(world.maxTokens ? { max_tokens: world.maxTokens } : {}),
      ...(world.temperature !== undefined ? { temperature: world.temperature } : {}),
      ...(world.amplification ? { amplification: world.amplification } : {}),
      include_diff: world.includeDiff ?? false,
      debug: world.debug ?? false
    })
  } catch (err) {
    world.error = err
  }
}

Given('the stream response text is {string}', function (text) {
  mockState().anthropic.streamText = text
})

Given('the stream fails with {string}', function (message) {
  mockState().anthropic.streamError = new Error(message)
})

Given('the stream fails on the first {int} calls with {string}', function (count, message) {
  const st = mockState().anthropic
  for (let i = 0; i < count; i++) {
    st.streamErrors.push(new Error(message))
  }
})

Given('temperature {float}', function (temperature) {
  this.temperature = temperature
})

Given('api key {string}', function (apiKey) {
  this.apiKey = apiKey
})

When('anthropicExplainPatch is called', async function () {
  await callAnthropic(this)
})

Then('{int} stream call was made', function (count) {
  expect(mockState().anthropic.streamCalls).to.have.lengthOf(count)
})

Then('{int} stream calls were made', function (count) {
  expect(mockState().anthropic.streamCalls).to.have.lengthOf(count)
})

Then('stream request {int} used model {string} temperature {float} and max tokens {int}', function (index, model, temperature, maxTokens) {
  const call = mockState().anthropic.streamCalls[index - 1]
  expect(call.model).to.equal(model)
  expect(call.temperature).to.equal(temperature)
  expect(call.max_tokens).to.equal(maxTokens)
})

Then('stream request {int} carries the system and user prompts', async function (index) {
  const { SYSTEM_PROMPT } = await import('../../src/utils.js')
  const call = mockState().anthropic.streamCalls[index - 1]
  expect(call.system).to.equal(SYSTEM_PROMPT)
  expect(call.messages).to.have.lengthOf(1)
  expect(call.messages[0].role).to.equal('user')
  expect(call.messages[0].content).to.contain('Repository: https://github.com/brave/pull-merge')
  expect(call.messages[0].content).to.contain(`\`\`\`\n${this.patchBody}\n\`\`\``)
})

Then('the Anthropic client was constructed with api key {string}', function (apiKey) {
  const args = mockState().anthropic.constructorArgs
  expect(args).to.have.lengthOf(1)
  expect(args[0]).to.deep.equal({ apiKey })
})

Then('no Anthropic client was constructed', function () {
  expect(mockState().anthropic.constructorArgs).to.have.lengthOf(0)
})

Then('the stream response was logged', function () {
  const logs = mockState().logs
  expect(logs.some((line) => line.includes('the review'))).to.equal(true)
})

When('the anthropic patch embedding property holds for {int} runs', async function (runs) {
  const { default: explainPatch } = await import('../../src/anthropicExplainPatch.js')
  mockState().tokenizer.count = () => 100000
  mockState().anthropic.streamText = 'review'
  const patchBody = fc.array(fc.constantFrom('a', 'b', ' ', '\n', '+', '-', '@', '/'), { maxLength: 40 }).map((chars) => chars.join(''))
  await fc.assert(fc.asyncProperty(patchBody, async (body) => {
    const out = await explainPatch({ apiKey: 'sk-ant-test', patchBody: body, owner: 'o', repo: 'r', models: ['claude-prop'] })
    const calls = mockState().anthropic.streamCalls
    const prompt = calls[calls.length - 1].messages[0].content
    expect(prompt).to.contain(`\`\`\`\n${body}\n\`\`\``)
    expect(out).to.equal('review\n</details>\n\n<!-- Generated by claude-prop -->')
  }), { numRuns: runs })
})
